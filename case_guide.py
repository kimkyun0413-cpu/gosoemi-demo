# ── 초안 점검 ───────────────────────────────────────────────────
_STATUTE_RE = re.compile(r"제\s*\d+\s*조(?:\s*의\s*\d+)?")
_CRIME_NAME_RE = re.compile(r"[가-힣]{1,8}죄")
_AMOUNT_RE = re.compile(r"(\d[\d,]*)\s*(만|천|억)?\s*원")
_FULL_DATE_RE = re.compile(r"(\d{4})\s*(?:년|[.\-/])\s*(\d{1,2})\s*(?:월|[.\-/])\s*(\d{1,2})")
_MONTH_DAY_RE = re.compile(r"(\d{1,2})\s*월\s*(\d{1,2})\s*일")
_PHONE_OR_ACCOUNT_RE = re.compile(r"\d{2,6}(?:-\d{2,6}){2,}")
_ISO_DATE_RE = re.compile(r"\d{4}-\d{1,2}-\d{1,2}")
_PEOPLE_COUNT_RE = re.compile(r"(\d+)\s*명")
# 고소인이 단정해서 적은 사실이 초안에서 추측처럼 바뀌었는지 볼 때 쓰는 표현(입력에 없을 때만 알린다)
_HEDGE_RE = re.compile(r"추측됩니다|추측합니다|(?:라고|다고) 생각합니다|것으로 보입니다|것 같습니다")


def _compact(text: str) -> str:
    return re.sub(r"[\s,]", "", text or "")


def _amounts(text: str) -> set:
    return {_compact(number) + (unit or "") for number, unit in _AMOUNT_RE.findall(text or "")}


def _dates(text: str) -> set:
    dates = {(int(m), int(d)) for _, m, d in _FULL_DATE_RE.findall(text or "")}
    dates |= {(int(m), int(d)) for m, d in _MONTH_DAY_RE.findall(text or "")}
    return dates


def find_unsupported_details(draft: str, case: dict, today_str: str = "") -> list:
    """초안에 들어 있지만 입력에서 찾을 수 없는 법조문·죄명·금액·날짜·번호를 찾아 안내 문구로 돌려준다.

    완벽한 검사는 아니며, 사용자가 제출 전에 직접 확인할 부분을 알려 주는 용도다.
    """
    source = "\n".join((case.get(key) or "") for _, key in CASE_FIELDS)
    source_compact = _compact(source)
    warnings = []

    statutes = sorted({_compact(s) for s in _STATUTE_RE.findall(draft)} - {_compact(s) for s in _STATUTE_RE.findall(source)})
    if statutes:
        warnings.append(f"법조문({', '.join(statutes)})이 들어 있습니다. 입력하지 않은 내용이니 지우거나 전문가에게 확인해 주세요.")

    crimes = sorted({c for c in _CRIME_NAME_RE.findall(draft) if c not in source and c not in ("범죄",)})
    if crimes:
        warnings.append(f"죄명({', '.join(crimes)})이 들어 있습니다. 범죄가 되는지는 수사기관이 판단하니, 직접 적은 내용이 아니라면 지우는 것이 안전합니다.")

    amounts = sorted(_amounts(draft) - _amounts(source))
    if amounts:
        warnings.append(f"입력에서 찾을 수 없는 금액({', '.join(a + '원' for a in amounts)})이 있습니다. 실제 금액인지 확인해 주세요.")

    today_parts = _FULL_DATE_RE.findall(today_str or "")
    today_key = {(int(m), int(d)) for _, m, d in today_parts}
    dates = sorted(_dates(draft) - _dates(source) - today_key)
    if dates:
        warnings.append(f"입력에서 찾을 수 없는 날짜({', '.join(f'{m}월 {d}일' for m, d in dates)})가 있습니다. 맞는 날짜인지 확인해 주세요.")

    numbers = sorted({
        n for n in _PHONE_OR_ACCOUNT_RE.findall(draft)
        if _compact(n) not in source_compact and not _ISO_DATE_RE.fullmatch(n)
    })
    if numbers:
        warnings.append(f"입력에서 찾을 수 없는 번호({', '.join(numbers)})가 있습니다. 연락처·계좌번호가 맞는지 확인해 주세요.")

    people = sorted(set(_PEOPLE_COUNT_RE.findall(draft)) - set(_PEOPLE_COUNT_RE.findall(source)), key=int)
    if people:
        warnings.append(f"입력에서 찾을 수 없는 인원({', '.join(p + '명' for p in people)})이 있습니다. 적은 사람 수와 같은지, 서로 다른 사람 수를 더한 숫자가 아닌지 확인해 주세요.")

    hedges = sorted({h for h in _HEDGE_RE.findall(draft) if h not in source})
    if hedges:
        warnings.append(f"입력에 없던 추측 표현({', '.join(hedges)})이 있습니다. 직접 단정해서 적은 사실이 추측처럼 바뀌지 않았는지 확인해 주세요.")

    return warnings


# ── Word 문서 ───────────────────────────────────────────────────
def _normalize_heading(line: str) -> str:
    text = re.sub(r"^[#>\s]+", "", line)
    text = text.replace("**", "").replace("__", "")
    text = re.sub(r"^(?:\d+|[一-十]|[가-하])\s*[.)]\s*", "", text)
    text = text.strip().strip("[]【】").rstrip(":：").strip()
    return text


def _clean_body_line(line: str) -> str:
    text = line.replace("**", "").replace("__", "")
    text = re.sub(r"^#+\s*", "", text)
    text = re.sub(r"^[*\-]\s+", "- ", text)
    return text


def build_case_draft_docx(draft_text: str) -> BytesIO:
    document = Document()

    section = document.sections[0]
    section.page_height = Mm(297)
    section.page_width = Mm(210)
    section.top_margin = Mm(20)
    section.bottom_margin = Mm(20)
    section.left_margin = Mm(20)
    section.right_margin = Mm(20)

    normal_style = document.styles["Normal"]
    normal_style.font.size = Pt(11)
    normal_style.paragraph_format.line_spacing = 1.5

    title_paragraph = document.add_paragraph()
    title_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_paragraph.add_run(DOCX_TITLE)
    title_run.bold = True
    title_run.font.size = Pt(20)

    document.add_paragraph()

    title_skipped = False
    skip_next_line = False
    for raw_line in with_draft_disclaimer(draft_text).splitlines():
        line = raw_line.strip()
        if not line:
            continue
        heading = _normalize_heading(line)
        if heading == "문서 제목":
            skip_next_line = True
            continue
        if skip_next_line:
            skip_next_line = False
            continue
        if heading == DOCX_TITLE and not title_skipped:
            title_skipped = True
            continue
        if heading in DOCX_SECTION_HEADERS:
            heading_paragraph = document.add_paragraph()
            heading_run = heading_paragraph.add_run(heading)
            heading_run.bold = True
            heading_run.font.size = Pt(13)
        else:
            document.add_paragraph(_clean_body_line(line))

    buffer = BytesIO()
    document.save(buffer)
    buffer.seek(0)
    return buffer
