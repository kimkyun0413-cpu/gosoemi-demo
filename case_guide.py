def is_missing(value) -> bool:
    text = (value or "").strip()
    return not text or text == MISSING_VALUE


def missing_info_items(case: dict) -> list:
    """비어 있거나 '모름' 등으로 적은 항목의 이름. 초안에서 확인 필요로 표시할 대상이다."""
    items = []
    for label, key in CASE_FIELDS:
        value = (case.get(key) or "").strip()
        if is_missing(value):
            items.append(f"{label} (입력하지 않음)")
        elif any(hint in value for hint in UNKNOWN_HINTS):
            items.append(f"{label} (모르는 부분 있음)")
    return items


def validate_case_values(field_values: dict) -> list:
    errors = []
    missing = [CASE_FIELD_LABELS[key] for key in CASE_REQUIRED_FIELDS if not (field_values.get(key) or "").strip()]
    if missing:
        errors.append("다음 항목은 꼭 적어 주세요: " + ", ".join(missing))
    for label, key in CASE_FIELDS:
        if len(field_values.get(key) or "") > CASE_FIELD_MAX_CHARS[key]:
            errors.append(f"{label}은(는) {CASE_FIELD_MAX_CHARS[key]}자까지 적을 수 있습니다. 조금 줄여 주세요.")
    return errors


def compute_case_fingerprint(user_id: str, field_values: dict) -> str:
    normalized = {key: (field_values.get(key) or "").strip() for _, key in CASE_FIELDS}
    payload = json.dumps({"user_id": user_id, "fields": normalized}, ensure_ascii=True, sort_keys=True)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


